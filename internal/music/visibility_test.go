// These tests exercise real uploaded test WAVs and persisted service state. The
// central fixture used by the HTTP test supplies an isolated account, not a real
// Wallet approval or evidence about deployed Music authentication.
func visibilityDraft(t *testing.T, s *Service, owner string) Track {
	t.Helper()
	if _, err := s.UpsertProfile(owner, Profile{DisplayName: "Visibility Creator", ExplicitAllowed: true}); err != nil {
		t.Fatal(err)
	}
	if _, err := s.OnboardCreator(owner, "Visibility Creator", "Owned test audio"); err != nil {
		t.Fatal(err)
	}
	track, err := s.UploadTrack(owner, TrackUpload{
		Title: "Private Test Tone", ArtistName: "Test Creator",
		Audio:           Upload{Reader: bytes.NewReader(toneWAV(1200))},
		AudioProvenance: "generated by internal/music toneWAV",
		RightsBasis:     "owned", Territories: []string{"TEST"}, EvidenceRef: "repository test fixture",
	})
	if err != nil {
		t.Fatal(err)
	}
	if track.ReleaseState != "draft" {
		t.Fatalf("uploaded fixture must begin as a private draft: %q", track.ReleaseState)
	}
	return track
}

func visibilityStateBytes(t *testing.T, s *Service) []byte {
	t.Helper()
	s.mu.RLock()
	defer s.mu.RUnlock()
	b, err := json.Marshal(s.state)
	if err != nil {
		t.Fatal(err)
	}
	return b
}

func visibilityReadFile(t *testing.T, path string) []byte {
	t.Helper()
	b, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	return b
}

func TestVisibilityReferenceWritesUseTrackAccessAndAreAtomic(t *testing.T) {
	s := testService(t)
	owner, actor := testAccount(t, 1), testAccount(t, 2)
	public := publishTrack(t, s, owner, false)
	draft := visibilityDraft(t, s, owner)
	withdrawn := publishTrack(t, s, owner, false)
	if _, err := s.SetRelease(owner, withdrawn.ID, "withdrawn", "author withdrawal"); err != nil {
		t.Fatal(err)
	}
	explicit := publishTrack(t, s, owner, true)
	ownDraft := visibilityDraft(t, s, actor)
	if _, err := s.UpsertProfile(actor, Profile{DisplayName: "Restricted Creator", ExplicitAllowed: false}); err != nil {
		t.Fatal(err)
	}

	cases := []struct {
		name string
		id   string
		err  error
	}{
		{"other draft", draft.ID, ErrNotFound},
		{"other withdrawn", withdrawn.ID, ErrNotFound},
		{"explicit blocked", explicit.ID, ErrUnauthorized},
		{"missing", "trk_missing", ErrNotFound},
		{"published", public.ID, nil},
		{"own draft", ownDraft.ID, nil},
	}
	ops := []struct {
		name string
		run  func(string) error
	}{
		{"playlist", func(id string) error {
			_, err := s.CreatePlaylist(actor, "Visibility List", "Owned test list", []string{public.ID, id})
			return err
		}},
		{"favorites", func(id string) error {
			_, err := s.UpdateLibrary(actor, []string{public.ID, id}, nil, nil)
			return err
		}},
		{"queue", func(id string) error {
			_, err := s.UpdateLibrary(actor, nil, []string{public.ID, id}, nil)
			return err
		}},
		{"downloads", func(id string) error {
			_, err := s.UpdateLibrary(actor, nil, nil, map[string]string{public.ID: "requested", id: "available"})
			return err
		}},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			if _, err := s.Track(actor, tc.id); !errors.Is(err, tc.err) {
				t.Fatalf("fixture does not match Track policy: got %v, want %v", err, tc.err)
			}
			for _, op := range ops {
				t.Run(op.name, func(t *testing.T) {
					before := visibilityStateBytes(t, s)
					disk := visibilityReadFile(t, s.cfg.StatePath)
					err := op.run(tc.id)
					if !errors.Is(err, tc.err) {
						t.Fatalf("reference write access = %v, want %v", err, tc.err)
					}
					if tc.err != nil && (!bytes.Equal(before, visibilityStateBytes(t, s)) || !bytes.Equal(disk, visibilityReadFile(t, s.cfg.StatePath))) {
						t.Fatal("rejected reference write changed persistent records or audit")
					}
				})
			}
		})
	}
}

func visibilityAssertListener(t *testing.T, got ListenerState, account, onlyID string) {
	t.Helper()
	if got.Account != account || !reflect.DeepEqual(got.Favorites, []string{onlyID}) || !reflect.DeepEqual(got.Queue, []string{onlyID}) ||
		!reflect.DeepEqual(got.Downloads, map[string]string{onlyID: "available"}) || !reflect.DeepEqual(got.Positions, map[string]int64{onlyID: 600}) ||
		len(got.History) != 1 || got.History[0].TrackID != onlyID {
		t.Fatalf("private collections contain hidden references or lose visible data: %#v", got)
	}
}

func TestVisibilityReadbackFiltersWithoutDeletingOriginalReferencesOrAudio(t *testing.T) {
	s := testService(t)
	owner, actor := testAccount(t, 3), testAccount(t, 4)
	visible := publishTrack(t, s, owner, false)
	withdrawn := publishTrack(t, s, owner, false)
	explicit := publishTrack(t, s, owner, true)
	if _, err := s.UpsertProfile(actor, Profile{DisplayName: "Library Listener", ExplicitAllowed: true}); err != nil {
		t.Fatal(err)
	}
	ids := []string{visible.ID, withdrawn.ID, explicit.ID}
	playlist, err := s.CreatePlaylist(actor, "Retained Library", "Visibility changes retain originals", ids)
	if err != nil {
		t.Fatal(err)
	}
	downloads := map[string]string{}
	for _, track := range []Track{visible, withdrawn, explicit} {
		downloads[track.ID] = "available"
		if _, _, err := s.SavePosition(actor, track.ID, "visibility-"+track.ID, 600, false); err != nil {
			t.Fatal(err)
		}
	}
	if _, err := s.UpdateLibrary(actor, ids, ids, downloads); err != nil {
		t.Fatal(err)
	}
	if _, err := s.SetRelease(owner, withdrawn.ID, "withdrawn", "author withdrawal"); err != nil {
		t.Fatal(err)
	}
	if _, err := s.UpsertProfile(actor, Profile{DisplayName: "Library Listener", ExplicitAllowed: false}); err != nil {
		t.Fatal(err)
	}
	rawBefore := visibilityStateBytes(t, s)
	diskBefore := visibilityReadFile(t, s.cfg.StatePath)
	audioBefore := map[string][]byte{}
	for _, track := range []Track{visible, withdrawn, explicit} {
		audioBefore[track.AudioFile] = visibilityReadFile(t, track.AudioFile)
	}

	check := func(t *testing.T, service *Service) {
		t.Helper()
		listener, err := service.Listener(actor)
		if err != nil {
			t.Fatal(err)
		}
		visibilityAssertListener(t, listener, actor, visible.ID)
		lists := service.Playlists(actor)
		if len(lists) != 1 || lists[0].ID != playlist.ID || !reflect.DeepEqual(lists[0].TrackIDs, []string{visible.ID}) {
			t.Fatalf("playlist list leaked hidden references: %#v", lists)
		}
		got, err := service.Playlist(actor, playlist.ID)
		if err != nil || !reflect.DeepEqual(got.TrackIDs, []string{visible.ID}) {
			t.Fatalf("individual playlist leaked hidden references: %#v %v", got, err)
		}
		snapshot, err := service.Snapshot(actor)
		if err != nil {
			t.Fatal(err)
		}
		visibilityAssertListener(t, snapshot["listener"].(ListenerState), actor, visible.ID)
		snapshotLists := snapshot["playlists"].([]Playlist)
		if len(snapshotLists) != 1 || !reflect.DeepEqual(snapshotLists[0].TrackIDs, []string{visible.ID}) {
			t.Fatalf("account snapshot bypassed playlist filtering: %#v", snapshotLists)
		}
		// A caller must not receive slices or maps backed by raw retained state.
		listener.Favorites[0] = "caller-change"
		listener.Queue[0] = "caller-change"
		listener.Downloads[visible.ID] = "removed"
		listener.Positions[visible.ID] = 999
		listener.History[0].TrackID = "caller-change"
		lists[0].TrackIDs[0] = "caller-change"
		got.TrackIDs[0] = "caller-change"
		if !bytes.Equal(rawBefore, visibilityStateBytes(t, service)) {
			t.Fatal("reading or changing returned values rewrote retained source references")
		}
		if !bytes.Equal(diskBefore, visibilityReadFile(t, service.cfg.StatePath)) {
			t.Fatal("readback changed the persisted source document")
		}
		for path, before := range audioBefore {
			if !bytes.Equal(before, visibilityReadFile(t, path)) {
				t.Fatal("visibility filtering changed an original audio file")
			}
		}
	}
	check(t, s)
	restarted, err := New(s.cfg)
	if err != nil {
		t.Fatal(err)
	}
	check(t, restarted)
	if _, err := restarted.SetRelease(owner, withdrawn.ID, "published", ""); err != nil {
		t.Fatal(err)
	}
	if _, err := restarted.UpsertProfile(actor, Profile{DisplayName: "Library Listener", ExplicitAllowed: true}); err != nil {
		t.Fatal(err)
	}
	restored, err := restarted.Playlist(actor, playlist.ID)
	if err != nil || !reflect.DeepEqual(restored.TrackIDs, ids) {
		t.Fatalf("allowed-again original playlist did not recover: %#v %v", restored, err)
	}
	listener, err := restarted.Listener(actor)
	if err != nil || !reflect.DeepEqual(listener.Favorites, ids) || !reflect.DeepEqual(listener.Queue, ids) || len(listener.Downloads) != 3 || len(listener.Positions) != 3 || len(listener.History) != 3 {
		t.Fatalf("allowed-again original listener state did not recover: %#v %v", listener, err)
	}
}

func TestVisibilityPlaylistUpdatePreservesHiddenOriginalsAndOwner(t *testing.T) {
	s := testService(t)
	owner, actor, intruder := testAccount(t, 5), testAccount(t, 6), testAccount(t, 7)
	visible := publishTrack(t, s, owner, false)
	hidden := publishTrack(t, s, owner, false)
	replacement := publishTrack(t, s, owner, false)
	newPrivate := visibilityDraft(t, s, owner)
	playlist, err := s.CreatePlaylist(actor, "Original List", "Original description", []string{visible.ID, hidden.ID})
	if err != nil {
		t.Fatal(err)
	}
	createdState := visibilityStateBytes(t, s)
	playlist.TrackIDs[0] = "caller-change"
	if !bytes.Equal(createdState, visibilityStateBytes(t, s)) {
		t.Fatal("changing the create response rewrote persisted playlist references")
	}
	if _, err := s.SetRelease(owner, hidden.ID, "withdrawn", "author withdrawal"); err != nil {
		t.Fatal(err)
	}
	updated, err := s.UpdatePlaylist(actor, playlist.ID, "Edited List", "Edited description", []string{replacement.ID, replacement.ID})
	if err != nil || updated.ID != playlist.ID || updated.Owner != actor || updated.Name != "Edited List" || updated.Description != "Edited description" ||
		!updated.CreatedAt.Equal(playlist.CreatedAt) || !reflect.DeepEqual(updated.TrackIDs, []string{replacement.ID}) {
		t.Fatalf("visible playlist edit failed: %#v %v", updated, err)
	}
	s.mu.RLock()
	raw := s.state.Playlists[playlist.ID]
	s.mu.RUnlock()
	if len(raw.TrackIDs) != 2 || !visibilityContains(raw.TrackIDs, hidden.ID) || !visibilityContains(raw.TrackIDs, replacement.ID) || visibilityContains(raw.TrackIDs, visible.ID) {
		t.Fatalf("editing visible content erased hidden originals or retained removed visible content: %#v", raw)
	}
	before := visibilityStateBytes(t, s)
	for _, tc := range []struct {
		name, actor string
		ids         []string
	}{
		{"cross account", intruder, []string{replacement.ID}},
		{"inject private ID", actor, []string{replacement.ID, newPrivate.ID}},
	} {
		t.Run(tc.name, func(t *testing.T) {
			if _, err := s.UpdatePlaylist(tc.actor, playlist.ID, "Rejected Edit", "", tc.ids); err == nil {
				t.Fatal("unauthorized playlist update succeeded")
			}
			if !bytes.Equal(before, visibilityStateBytes(t, s)) {
				t.Fatal("rejected playlist update changed records or audit")
			}
		})
	}
	if _, err := s.Playlist(intruder, playlist.ID); err == nil || len(s.Playlists(intruder)) != 0 {
		t.Fatalf("another account can read a private playlist: %v", err)
	}
	restarted, err := New(s.cfg)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := restarted.SetRelease(owner, hidden.ID, "published", ""); err != nil {
		t.Fatal(err)
	}
	restored, err := restarted.Playlist(actor, playlist.ID)
	if err != nil || len(restored.TrackIDs) != 2 || !visibilityContains(restored.TrackIDs, hidden.ID) || !visibilityContains(restored.TrackIDs, replacement.ID) {
		t.Fatalf("hidden playlist original did not recover after restart and re-release: %#v %v", restored, err)
	}
}

func visibilityContains(ids []string, want string) bool {
	for _, id := range ids {
		if id == want {
			return true
		}
	}
	return false
}

func TestVisibilityLibraryEditPreservesUnavailableOriginals(t *testing.T) {
	s := testService(t)
	owner, actor := testAccount(t, 9), testAccount(t, 10)
	removed := publishTrack(t, s, owner, false)
	hidden := publishTrack(t, s, owner, false)
	added := publishTrack(t, s, owner, false)
	if _, err := s.UpdateLibrary(actor, []string{removed.ID, hidden.ID}, []string{removed.ID, hidden.ID}, map[string]string{removed.ID: "available", hidden.ID: "available"}); err != nil {
		t.Fatal(err)
	}
	if _, err := s.SetRelease(owner, hidden.ID, "withdrawn", "author withdrawal"); err != nil {
		t.Fatal(err)
	}
	got, err := s.UpdateLibrary(actor, []string{added.ID}, []string{added.ID}, map[string]string{added.ID: "requested"})
	if err != nil || !reflect.DeepEqual(got.Favorites, []string{added.ID}) || !reflect.DeepEqual(got.Queue, []string{added.ID}) || !reflect.DeepEqual(got.Downloads, map[string]string{added.ID: "requested"}) {
		t.Fatalf("visible library edit = %#v %v", got, err)
	}
	s.mu.RLock()
	raw := s.state.Listeners[actor]
	s.mu.RUnlock()
	if len(raw.Favorites) != 2 || !visibilityContains(raw.Favorites, hidden.ID) || !visibilityContains(raw.Favorites, added.ID) ||
		len(raw.Queue) != 2 || !visibilityContains(raw.Queue, hidden.ID) || !visibilityContains(raw.Queue, added.ID) ||
		!reflect.DeepEqual(raw.Downloads, map[string]string{added.ID: "requested", hidden.ID: "available"}) {
		t.Fatalf("library edit failed to retain unavailable originals: %#v", raw)
	}
	restarted, err := New(s.cfg)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := restarted.SetRelease(owner, hidden.ID, "published", ""); err != nil {
		t.Fatal(err)
	}
	restored, err := restarted.Listener(actor)
	if err != nil || !reflect.DeepEqual(restored.Favorites, raw.Favorites) || !reflect.DeepEqual(restored.Queue, raw.Queue) || !reflect.DeepEqual(restored.Downloads, raw.Downloads) {
		t.Fatalf("library originals did not recover when access returned: %#v %v", restored, err)
	}
}

func TestVisibilityPlaylistChecksCurrentAccessWhenCommitting(t *testing.T) {
	s := testService(t)
	owner, actor := testAccount(t, 11), testAccount(t, 12)
	track := publishTrack(t, s, owner, false)
	if _, err := s.Track(actor, track.ID); err != nil {
		t.Fatal(err)
	}
	// CreatePlaylist obtains its creation timestamp before entering mutate.
	// Inject a withdrawal at that deterministic boundary: any validation based
	// only on a prior read must be rechecked against the transaction snapshot.
	originalNow := s.cfg.Now
	withdraw := true
	var afterWithdrawal []byte
	s.cfg.Now = func() time.Time {
		if withdraw {
			withdraw = false
			if _, err := s.SetRelease(owner, track.ID, "withdrawn", "concurrent author withdrawal"); err != nil {
				t.Fatal(err)
			}
			afterWithdrawal = visibilityStateBytes(t, s)
		}
		return originalNow()
	}
	if _, err := s.CreatePlaylist(actor, "Pending List", "", []string{track.ID}); !errors.Is(err, ErrNotFound) {
		t.Fatalf("playlist accepted a track withdrawn before commit: %v", err)
	}
	if withdraw || !bytes.Equal(afterWithdrawal, visibilityStateBytes(t, s)) || len(s.Playlists(actor)) != 0 {
		t.Fatal("rejected pending playlist changed source records after withdrawal")
	}
	if err := s.VerifyIntegrity(); err != nil {
		t.Fatal(err)
	}
}

func TestVisibilityPlaylistHTTPReadEditAndAccountBoundary(t *testing.T) {
	s := testService(t)
	f := testFixture(t)
	central := centralAuth(t, s, f)
	defer central.Close()
	owner := testAccount(t, 8)
	visible := publishTrack(t, s, owner, false)
	hidden := publishTrack(t, s, owner, false)
	foreign, err := s.CreatePlaylist(owner, "Another Private List", "Private", []string{visible.ID})
	if err != nil {
		t.Fatal(err)
	}
	h := NewServer(s, "https://music.ynx.test", nil).Handler()
	for _, route := range []struct{ method, path string }{
		{http.MethodGet, "/api/playlists"},
		{http.MethodGet, "/api/playlists/" + foreign.ID},
		{http.MethodPut, "/api/playlists/" + foreign.ID},
	} {
		unauthorized := protected(t, h, route.method, route.path, nil, authFixture{})
		if unauthorized.Code != http.StatusUnauthorized {
			t.Fatalf("unauthenticated %s %s = %d", route.method, route.path, unauthorized.Code)
		}
	}
	w := protected(t, h, http.MethodPost, "/api/playlists", map[string]any{"name": "HTTP List", "description": "Original", "trackIds": []string{visible.ID, hidden.ID}}, f)
	if w.Code != http.StatusCreated {
		t.Fatalf("create playlist = %d %s", w.Code, w.Body.String())
	}
	var playlist Playlist
	if err := json.Unmarshal(w.Body.Bytes(), &playlist); err != nil || playlist.ID == "" {
		t.Fatalf("invalid created playlist: %s %v", w.Body.String(), err)
	}
	if _, err := s.SetRelease(owner, hidden.ID, "withdrawn", "author withdrawal"); err != nil {
		t.Fatal(err)
	}
	w = protected(t, h, http.MethodGet, "/api/playlists", nil, f)
	var lists []Playlist
	if w.Code != http.StatusOK || json.Unmarshal(w.Body.Bytes(), &lists) != nil || len(lists) != 1 || lists[0].ID != playlist.ID || !reflect.DeepEqual(lists[0].TrackIDs, []string{visible.ID}) {
		t.Fatalf("read playlists = %d %s", w.Code, w.Body.String())
	}
	w = protected(t, h, http.MethodGet, "/api/playlists/"+playlist.ID, nil, f)
	var got Playlist
	if w.Code != http.StatusOK || json.Unmarshal(w.Body.Bytes(), &got) != nil || !reflect.DeepEqual(got.TrackIDs, []string{visible.ID}) {
		t.Fatalf("read playlist = %d %s", w.Code, w.Body.String())
	}
	w = protected(t, h, http.MethodPut, "/api/playlists/"+playlist.ID, map[string]any{"name": "Renamed HTTP List", "description": "Updated", "trackIds": []string{visible.ID}}, f)
	if w.Code != http.StatusOK || json.Unmarshal(w.Body.Bytes(), &got) != nil || got.Name != "Renamed HTTP List" || got.Description != "Updated" || !reflect.DeepEqual(got.TrackIDs, []string{visible.ID}) {
		t.Fatalf("edit playlist = %d %s", w.Code, w.Body.String())
	}
	before := visibilityStateBytes(t, s)
	for _, method := range []string{http.MethodGet, http.MethodPut} {
		var body any
		if method == http.MethodPut {
			body = map[string]any{"name": "Stolen List", "trackIds": []string{visible.ID}}
		}
		w = protected(t, h, method, "/api/playlists/"+foreign.ID, body, f)
		if w.Code != http.StatusForbidden && w.Code != http.StatusNotFound {
			t.Fatalf("cross-owner %s = %d %s", method, w.Code, w.Body.String())
		}
	}
	if !bytes.Equal(before, visibilityStateBytes(t, s)) {
		t.Fatal("cross-account HTTP requests changed private records")
	}
	if err := s.VerifyIntegrity(); err != nil {
		t.Fatalf("playlist route operations broke persistence integrity: %v", err)
	}
}
