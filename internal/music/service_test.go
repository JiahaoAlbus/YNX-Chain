func TestPlaybackPositionRecoveryAndUsageIdempotency(t *testing.T) {
	s := testService(t)
	creator := testAccount(t, 1)
	listener := testAccount(t, 2)
	track := publishTrack(t, s, creator, false)
	if _, e := s.UpsertProfile(listener, Profile{DisplayName: "Listener", PrivateHistory: true}); e != nil {
		t.Fatal(e)
	}
	l, u, e := s.SavePosition(listener, track.ID, "session-1", 1100, true)
	if e != nil {
		t.Fatal(e)
	}
	if l.Positions[track.ID] != 1100 || u == nil || u.ListenedMillis != 1100 {
		t.Fatalf("unexpected persisted playback: %#v %#v", l, u)
	}
	_, u2, e := s.SavePosition(listener, track.ID, "session-1", 1150, true)
	if e != nil {
		t.Fatal(e)
	}
	if u2.ID != u.ID {
		t.Fatalf("completion replay created a second usage record")
	}
	restarted, e := New(s.cfg)
	if e != nil {
		t.Fatal(e)
	}
	got, e := restarted.Listener(listener)
	if e != nil || got.Positions[track.ID] != 1150 {
		t.Fatalf("position did not recover after restart: %#v %v", got, e)
	}
	if len(restarted.Usage(creator)) != 1 {
		t.Fatalf("usage replay was not idempotent")
	}
	mediaPath, mediaType, e := restarted.Media(listener, track.ID, "audio")
	if e != nil || mediaPath == "" || mediaType != "audio/wav" {
		t.Fatalf("media path did not recover after restart: path=%q type=%q err=%v", mediaPath, mediaType, e)
	}
	if _, e := os.Stat(mediaPath); e != nil {
		t.Fatalf("recovered media path is unavailable: %v", e)
	}
}

