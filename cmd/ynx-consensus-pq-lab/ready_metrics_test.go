type pqLabReadyObservedInput struct {
	reader   io.Reader
	out      *bytes.Buffer
	t        *testing.T
	observed bool
}

func (r *pqLabReadyObservedInput) Read(p []byte) (int, error) {
	if !r.observed {
		r.observed = true
		lines := bytes.Split(bytes.TrimSpace(r.out.Bytes()), []byte("\n"))
		if len(lines) != 1 {
			r.t.Fatal("real ready was not emitted before first command read")
		}
		var ready map[string]any
		if json.Unmarshal(lines[0], &ready) != nil || ready["version"] != "YNX-PQ-LAB-SENDER-READY/v1" || ready["signed"] != false || ready["nonceReserved"] != false || ready["authorityGranted"] != false {
			r.t.Fatal("ready fabricated signature/nonce/authority")
		}
	}
	return r.reader.Read(p)
}
func TestPQLabSenderPUBLICReadyBeforeCommandsAndSeparateColdCost(t *testing.T) {
	created, pin, height, appHash := pqLabSenderCommandFixture(t, true)
	directory := filepath.Join(created.Plan.RootDir, "workload")
	credential, err := os.Open(filepath.Join(directory, "private-senders", "recovery.raw"))
	if err != nil {
		t.Fatal(err)
	}
	defer credential.Close()
	args := []string{"--synthetic", "--root", created.Plan.RootDir, "--plan-sha256", created.PlanSHA256, "--workload-sha256", pin, "--owner", "0", "--credential-fd", strconv.Itoa(int(credential.Fd())), "--ready", "--timings"}
	// Handshake-only startup neither consumes a transaction command nor creates
	// an operation, signs in advance or reserves nonce for future demand.
	var out bytes.Buffer
	input := &pqLabReadyObservedInput{reader: strings.NewReader(""), out: &out, t: t}
	if err = runPQLabSenderInput(args, input, &out); err != nil {
		t.Fatal(err)
	}
	entries, err := os.ReadDir(filepath.Join(directory, "sender-public", "0000"))
	if err != nil || len(entries) != 0 {
		t.Fatal("startup reserved transaction history/nonce")
	}
	var ready struct {
		Version          string
		StartupElapsedNS int64
		Timings          consensus.PQLabMetricsSnapshot
	}
	if json.Unmarshal(bytes.TrimSpace(out.Bytes()), &ready) != nil || ready.StartupElapsedNS <= 0 || ready.Timings.Stages["sender.openTotal"].Calls != 1 || ready.Timings.Stages["sender.pbkdf2_600000"].Calls != 1 || ready.Timings.Stages["sender.importFullPrivatePublicPair"].Calls != 1 {
		t.Fatal("ready did not include real cold Open/KDF/import")
	}
	command := pqLabSenderCommand{Version: "YNX-PQ-LAB-SENDER-COMMAND/v1", Operation: "sign", Request: consensus.PQLabSenderRequest{Version: "YNX-PQ-LAB-SENDER-REQUEST/v1", OperationID: strings.Repeat("e", 64), OwnerIndex: 0, FirstNonce: 2, Members: 1}, CheckpointHeight: height, CheckpointAppHash: appHash}
	raw, _ := json.Marshal(command)
	out.Reset()
	input = &pqLabReadyObservedInput{reader: bytes.NewReader(append(raw, '\n')), out: &out, t: t}
	if err = runPQLabSenderInput(args, input, &out); err != nil {
		t.Fatal(err)
	}
	lines := bytes.Split(bytes.TrimSpace(out.Bytes()), []byte("\n"))
	if len(lines) != 2 {
		t.Fatal("ready and command replies not separate")
	}
	var reply struct {
		Code             string
		Result           consensus.PQLabSenderResult
		Timings          consensus.PQLabMetricsSnapshot
		StaticCache      consensus.PQLabStaticCacheStats
		CalleeElapsedNS  int64
		StartupElapsedNS int64
		StartupTimings   consensus.PQLabMetricsSnapshot
	}
	if json.Unmarshal(lines[1], &reply) != nil || reply.Code != "ORIGINAL_SAVED" || reply.Result.Transaction.Members != "1" || reply.CalleeElapsedNS <= 0 || reply.StaticCache.Entries != 1 || reply.Timings.Stages["checkpoint.nodeReadAndValidate"].Calls != 12 || reply.Timings.Stages["sender.openTotal"].Calls != 0 || reply.StartupElapsedNS <= 0 || reply.StartupTimings.Stages["sender.openTotal"].Calls != 1 {
		t.Fatal("actual command/cold costs or dynamic checks conflated")
	}
	// Existing/pending command is reconciled through original recovery. No new
	// nonce or signature is generated by the readiness or metrics protocol.
	command.Operation = "recover"
	command.CheckpointHeight = 0
	command.CheckpointAppHash = ""
	raw, _ = json.Marshal(command)
	args = args[:len(args)-2]
	out.Reset()
	if err = runPQLabSenderInput(args, bytes.NewReader(raw), &out); err != nil {
		t.Fatal(err)
	}
	var recovered struct {
		Code   string
		Result consensus.PQLabSenderResult
	}
	if json.Unmarshal(out.Bytes(), &recovered) != nil || recovered.Code != "ORIGINAL_RECOVERED" || recovered.Result.Transaction.Wire != reply.Result.Transaction.Wire {
		t.Fatal("metrics/ready changed original UNKNOWN recovery")
	}
}

func TestPQLabSenderPUBLICTimingsWithoutReadyRetainsColdCost(t *testing.T) {
	created, pin, _, _ := pqLabSenderCommandFixture(t, true)
	directory := filepath.Join(created.Plan.RootDir, "workload")
	credential, err := os.Open(filepath.Join(directory, "private-senders", "recovery.raw"))
	if err != nil {
		t.Fatal(err)
	}
	defer credential.Close()
	args := []string{"--synthetic", "--root", created.Plan.RootDir, "--plan-sha256", created.PlanSHA256, "--workload-sha256", pin, "--owner", "0", "--credential-fd", strconv.Itoa(int(credential.Fd())), "--timings"}
	command := pqLabSenderCommand{Version: "YNX-PQ-LAB-SENDER-COMMAND/v1", Operation: "recover", Request: consensus.PQLabSenderRequest{Version: "YNX-PQ-LAB-SENDER-REQUEST/v1", OperationID: strings.Repeat("f", 64), OwnerIndex: 0, FirstNonce: 2, Members: 1}}
	raw, _ := json.Marshal(command)
	var out bytes.Buffer
	if err = runPQLabSenderInput(args, bytes.NewReader(raw), &out); err != nil {
		t.Fatal(err)
	}
	var reply struct {
		Code             string
		StartupElapsedNS int64
		StartupTimings   consensus.PQLabMetricsSnapshot
	}
	if json.Unmarshal(out.Bytes(), &reply) != nil || reply.Code != "UNKNOWN" || reply.StartupElapsedNS <= 0 || reply.StartupTimings.Stages["sender.pbkdf2_600000"].Calls != 1 {
		t.Fatal("timings-only hid cold cost or replayed unknown")
	}
}
