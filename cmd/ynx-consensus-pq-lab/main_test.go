func TestPQLabNormalCommandOnlineIndependentOwnerFlags(t *testing.T) {
	parent, err := filepath.EvalSymlinks(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	root := filepath.Join(parent, "online-lab")
	var out bytes.Buffer
	if err = run([]string{"create", "--synthetic", "--root", root, "--owners", "2", "--online", "--transactions", "2", "--batch-size", "1"}, &out); err != nil {
		t.Fatal(err)
	}
	var result createResult
	if err = json.Unmarshal(out.Bytes(), &result); err != nil {
		t.Fatal(err)
	}
	if result.Workload.Mode != "online" || len(result.Workload.Owners) != 2 || result.Workload.OwnerCapacity != "2" || len(result.Workload.Transactions) != 0 || result.NodeStarted || result.PQQuorumVerified {
		t.Fatal("normal create dropped independent online owner flags")
	}
	if result.Workload.Owners[0].Owner == result.Workload.Owners[1].Owner {
		t.Fatal("independent owners share identity")
	}
	for _, value := range []string{"0", "1001"} {
		var rejected bytes.Buffer
		if err = run([]string{"create", "--synthetic", "--root", filepath.Join(parent, "bad-"+value), "--owners", value}, &rejected); err == nil || rejected.Len() != 0 {
			t.Fatal("invalid explicit owner count accepted", value, err)
		}
	}
}

// Explicit integration fixture generated by the normal consensus test with
// REAL signed original disk stores. It is never synthesized by this CLI test.
func TestPQLabExportCommandOriginalStoppedStoreFixture(t *testing.T) {
	root := os.Getenv("YNX_PQ_LAB_STOPPED_FIXTURE_ROOT")
	if root == "" {
		t.Skip("explicit original stopped-store fixture not supplied")
	}
	raw, err := os.ReadFile(filepath.Join(root, "export-options.json"))
	if err != nil {
		t.Fatal(err)
	}
	var o consensus.PQLabExportOptions
	if err = json.Unmarshal(raw, &o); err != nil {
		t.Fatal(err)
	}
	output := filepath.Join(root, "normal-command-export")
	args := []string{"export", "--synthetic", "--root", root, "--plan-sha256", o.PlanSHA256, "--activation-sha256", o.ActivationSHA256, "--transaction", o.TransactionFile, "--transaction-sha256", o.TransactionSHA256, "--native-wire-hash", o.NativeWireHash, "--output", output, "--trusting-period", "1h", "--max-clock-drift", "1m", "--trust-numerator", "1", "--trust-denominator", "3"}
	var out bytes.Buffer
	if err = run(args, &out); err != nil {
		t.Fatal("actual normal export command", err)
	}
	var result consensus.PQLabStoppedProofExport
	if err = json.Unmarshal(out.Bytes(), &result); err != nil {
		t.Fatal(err)
	}
	if result.StoppedNodes != 4 || result.AuthorityGranted || result.PublicNetwork || result.NodeStarted || result.TransactionHash != o.TransactionSHA256 {
		t.Fatal("export command evidence scope changed")
	}
	var context bytes.Buffer
	if err = run([]string{"proof-context", "--synthetic", "--materials", result.Materials.Path, "--materials-sha256", result.Materials.SHA256, "--proof", result.Proof.Path, "--output", filepath.Join(root, "normal-command-context")}, &context); err != nil {
		t.Fatal("normal exported material consumer", err)
	}
	if !strings.Contains(context.String(), `"executionSuccessful":true`) {
		t.Fatal("normal proof context did not verify original execution")
	}
	before, err := os.ReadFile(filepath.Join(output, "result.json"))
	if err != nil {
		t.Fatal(err)
	}
	if err = run(args, &bytes.Buffer{}); err == nil {
		t.Fatal("normal command overwrote existing export")
	}
	after, err := os.ReadFile(filepath.Join(output, "result.json"))
	if err != nil || !bytes.Equal(before, after) {
		t.Fatal("original export changed on retry", err)
	}
}

