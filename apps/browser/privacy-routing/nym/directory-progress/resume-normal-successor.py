def load_gate():
    import hashlib
    if hashlib.sha256(BASE_GATE.read_bytes()).hexdigest() != BASE_GATE_SHA:
        raise RuntimeError("base-gate-pin")
    spec = importlib.util.spec_from_file_location("frozen_normal_builder", BASE_GATE)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def confirm_original(gate, body, guard, plan):
    original = gate.WORK / "build"
    body.require_hashes(guard, {original / name: sha for name, sha in ORIGINAL_BUILD_PINS.items()})
    data = gate.read(original / "receipt.json")
    gate.require(data["schema"] == "P05_NYM_NORMAL_OFFLINE_TERMINAL_V1"
                 and data["phase"] == "build" and data["planSHA256"] == BASE_PLAN_SHA
                 and data["firstFailure"] == {"type": "RuntimeError", "cause": "resource-interrupted-450s-work"}
                 and data["remainingOwned"] == [] and data["cleanupFailure"] is None
                 and data["childOutcomeRecordingFailure"] is None and data["cancelSignals"] == []
                 and data["result"] is None and data["publicNetwork"] is False
                 and data["productionRelease"] is False and 450 <= data["elapsedSeconds"] <= 465,
                 "original-stop-not-resumable")
    gate.require(len(data["steps"]) == 1 and gate.read(original / "steps.json") == data["steps"]
                 and gate.read(original / "start.json")["PID"] == ORIGINAL_PID,
                 "original-stage-identity")
    step = data["steps"][0]
    gate.require(step["name"] == "offline-cargo" and step["argv"] == plan["argv"]
                 and step["pid"] == step["pgid"] == ORIGINAL_CARGO and step["exit"] == -2
                 and step["reaped"] is True and step["terminalOutcome"] == "ORIGINAL_POPEN_WAIT",
                 "original-wait-not-confirmed")
    gate.require(not gate.ARTIFACT.exists(), "original-unexpected-artifact")
    original_pids = guard.processes()
    gate.require(not any(pid in original_pids for pid in (ORIGINAL_PID, ORIGINAL_CARGO))
                 and all(row["pgid"] != ORIGINAL_CARGO for row in original_pids.values()),
                 "original-process-or-group-not-clear")


def roots(gate):
    return {"source": gate.SOURCE, "cargo-home": gate.CARGO_HOME,
            "target": gate.TARGET, "tmp": gate.WORK / "build/tmp"}


def cache_state(gate, body, guard, tick=lambda: None):
    directories = {}
    files = {}
    for name, path in roots(gate).items():
        tick()
        st = path.lstat()
        gate.require(path.resolve() == path and stat.S_ISDIR(st.st_mode) and st.st_uid == os.getuid(),
                     "workspace-path:" + name)
        directories[name] = [str(path), st.st_dev, st.st_ino, st.st_mode]
        # Cache-generated bytes are identified by inode, size and timestamps.
        # Source bytes and dependency bytes are verified independently of this ledger.
        files[name] = gate.metadata(gate.inventory(body, path))
    body.require_hashes(guard, {gate.TARGET / FINGERPRINT: FINGERPRINT_SHA})
    return {"roots": directories, "files": files, "procMacroFingerprintSHA256": FINGERPRINT_SHA}


def check_source(gate, body, guard, stage, monitor):
    source_meta = gate.confirm_source(body, guard, stage["sourceReceiptSHA256"])
    actual = gate.verify_bytes(body, guard, gate.SOURCE, gate.read(gate.MANIFEST), monitor)
    return gate.verify_source_after(source_meta, actual)


def prepare(gate, body, guard, plan, stage, path):
    gate.require(not path.exists(), "resume-plan-already-sealed")
    changes = check_source(gate, body, guard, stage, lambda: None)
    state = cache_state(gate, body, guard)
    ledger = gate.WORK / "resume-continuity.json"
    body.dump_new(ledger, state)
    resume = {
        "schema": "P05_NYM_EXACT_NORMAL_COLD_RESUME_V1",
        "originalPlanSHA256": BASE_PLAN_SHA, "originalStageReceiptSHA256": STAGE_SHA,
        "originalBuildReceiptSHA256": ORIGINAL_BUILD_PINS["receipt.json"],
        "originalCargoStderrSHA256": ORIGINAL_BUILD_PINS["offline-cargo.stderr.log"],
        "resumeControllerSHA256": guard.sha(__file__), "ledgerSHA256": guard.sha(ledger),
        "originalControllerWait": 1, "originalCargoWait": -2, "originalCargoReaped": True,
        "originalRemainingOwned": [], "sourceMetadataChanges": changes,
        "directoryIdentities": state["roots"], "ledgerFileCounts": {
            name: len(rows) for name, rows in state["files"].items()},
        "sourceTreeSHA256": plan["candidateTreeSHA256"], "argv": plan["argv"],
        "environment": {**plan["environment"], "HOME": ORIGINAL_HOME,
                        "TMPDIR": str(roots(gate)["tmp"]) + "/"},
        "budgets": plan["budgetEachStageAndBuild"], "sharedLock": plan["sharedLock"],
        "state": "RESUME_PREPARED_NOT_RUN", "publicNetwork": False, "productionRelease": False,
    }
    body.dump_new(path, resume)
    print(json.dumps({"plan": str(path), "SHA256": guard.sha(path),
                      "ledger": str(ledger), "ledgerSHA256": guard.sha(ledger),
                      "counts": resume["ledgerFileCounts"]}))


def resume_plan(gate, body, guard, plan, path, pin):
    body.require_hashes(guard, {path: pin})
    data = gate.read(path)
    ledger = gate.WORK / "resume-continuity.json"
    body.require_hashes(guard, {ledger: data["ledgerSHA256"]})
    gate.require(data["schema"] == "P05_NYM_EXACT_NORMAL_COLD_RESUME_V1"
                 and data["resumeControllerSHA256"] == guard.sha(__file__)
                 and data["originalPlanSHA256"] == BASE_PLAN_SHA
                 and data["originalStageReceiptSHA256"] == STAGE_SHA
                 and data["originalBuildReceiptSHA256"] == ORIGINAL_BUILD_PINS["receipt.json"]
                 and data["sourceTreeSHA256"] == plan["candidateTreeSHA256"]
                 and data["budgets"] == plan["budgetEachStageAndBuild"]
                 and data["argv"] == plan["argv"]
                 and data["environment"] == {**plan["environment"], "HOME": ORIGINAL_HOME,
                                             "TMPDIR": str(roots(gate)["tmp"]) + "/"}
                 and data["publicNetwork"] is False and data["productionRelease"] is False,
                 "resume-plan-binding")
    return data, gate.read(ledger)


def build(gate, body, guard, plan, stage, data, expected, resume_pin):
    case = gate.WORK / "build-resumed"

    def action(owner, tmp):
        gate.require(cache_state(gate, body, guard, owner.monitor) == expected, "resume-workspace-continuity")
        initial_changes = check_source(gate, body, guard, stage, owner.monitor)
        gate.require(initial_changes == data["sourceMetadataChanges"], "resume-source-metadata")
        tool = Path(plan["environment"]["RUSTC"]).parent.parent
        guard.verify_manifest(tool, plan["toolchain"]["path"])
        gate.require(os.environ.get("HOME") == ORIGINAL_HOME, "original-environment-home")
        gate.observed_step(owner, data["environment"], "offline-cargo", plan["argv"], 0, 420)
        target = gate.TARGET / "release" / gate.TARGET_PROGRAM
        gate.require(target.is_file() and not target.is_symlink(), "build-target")
        gate.ARTIFACT.parent.mkdir(mode=0o700)
        import shutil
        with target.open("rb") as source, gate.ARTIFACT.open("xb") as output:
            shutil.copyfileobj(source, output)
        gate.ARTIFACT.chmod(0o500)
        digest = guard.sha(gate.ARTIFACT)
        gate.require(digest not in (gate.PINS[gate.OLD_RUNTIME], gate.PINS[gate.QA_RUNTIME]), "artifact-is-prior-supply")
        private_home = case / "probe-home"
        private_home.mkdir(mode=0o700)
        probe_env = {"PATH": "/usr/bin:/bin", "TMPDIR": str(tmp), "NYM_HOME_DIR": str(private_home)}
        for name, argv, exit_code in gate.probes():
            gate.observed_step(owner, probe_env, name, argv, exit_code)
        gate.require(not any(private_home.iterdir()), "probe-profile-side-effects")
        proof = gate.runtime_proof(guard, case)
        source_changes = check_source(gate, body, guard, stage, owner.monitor)
        body.require_hashes(guard, gate.PINS)
        body.require_hashes(guard, {gate.ARTIFACT: digest})
        return {"artifact": {"path": str(gate.ARTIFACT), "sha256": digest,
                             "bytes": gate.ARTIFACT.stat().st_size},
                "resumePlanSHA256": resume_pin, "sourceManifestSHA256": gate.PINS[gate.MANIFEST],
                "sourceMetadataChanges": source_changes, "CargoLockSHA256": plan["CargoLockSHA256"],
                "runtimeProof": proof, "upstreamTLSOrNetworkRun": False, "productionEligibility": False}

    return gate.make_owner(body, guard, "build-resumed", case, action)


def verify(gate, body, guard, plan, stage, data, resume_pin, terminal_pin):
    result = gate.terminal(body, guard, "build-resumed", terminal_pin,
                           [("offline-cargo", plan["argv"], 0), *gate.probes()])
    st = gate.ARTIFACT.lstat()
    binary = result["artifact"]
    gate.require(result["resumePlanSHA256"] == resume_pin
                 and result["sourceManifestSHA256"] == gate.PINS[gate.MANIFEST]
                 and result["CargoLockSHA256"] == plan["CargoLockSHA256"]
                 and result["sourceMetadataChanges"] == check_source(gate, body, guard, stage, lambda: None)
                 and result["upstreamTLSOrNetworkRun"] is False and result["productionEligibility"] is False
                 and binary["path"] == str(gate.ARTIFACT) and st.st_size == binary["bytes"] and st.st_nlink == 1
                 and st.st_uid == os.getuid() and stat.S_ISREG(st.st_mode) and stat.S_IMODE(st.st_mode) == 0o500
                 and binary["sha256"] not in (gate.PINS[gate.OLD_RUNTIME], gate.PINS[gate.QA_RUNTIME]),
                 "resumed-artifact")
    body.require_hashes(guard, {gate.ARTIFACT: binary["sha256"]})
    gate.require(gate.runtime_proof(guard, gate.WORK / "build-resumed") == result["runtimeProof"],
                 "resumed-runtime-proof-drift")
    print(json.dumps({"status": "OFFLINE_RESUMED_NORMAL_CANDIDATE_VERIFIED", "artifact": binary,
                      "originalBuildReceiptSHA256": data["originalBuildReceiptSHA256"],
                      "resumedBuildReceiptSHA256": terminal_pin, "productionEligibility": False}))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("operation", choices=("prepare", "check", "build", "verify"))
    parser.add_argument("--resume-plan-sha256")
    parser.add_argument("--build-receipt-sha256")
    args = parser.parse_args()
    gate = load_gate()
    body, guard = gate.load_owner()
    gate.require_workspace()
    plan = gate.checked_plan(body, guard)
    body.require_hashes(guard, {gate.PLAN: BASE_PLAN_SHA})
    gate.require(gate.read(gate.PLAN) == plan, "original-plan-binding")
    stage = gate.terminal(body, guard, "stage", STAGE_SHA, gate.cache_stage_steps())
    confirm_original(gate, body, guard, plan)
    path = gate.INPUTS / "OFFLINE_BUILD_RESUME_V1.json"
    if args.operation == "prepare":
        prepare(gate, body, guard, plan, stage, path)
        return 0
    data, state = resume_plan(gate, body, guard, plan, path, args.resume_plan_sha256)
    if args.operation == "check":
        gate.require(cache_state(gate, body, guard) == state, "resume-workspace-continuity")
        changes = check_source(gate, body, guard, stage, lambda: None)
        gate.require(changes == data["sourceMetadataChanges"], "resume-source-metadata")
        print(json.dumps({"status": "SAME_PATH_CONTINUITY_VERIFIED", "CargoStarted": False,
                          "originalWait": 1, "originalCargoWait": -2,
                          "ledgerSHA256": data["ledgerSHA256"]}))
        return 0
    gate.ARTIFACT = gate.WORK / "build-resumed/artifact/nym-socks5-client"
    if args.operation == "verify":
        verify(gate, body, guard, plan, stage, data, args.resume_plan_sha256, args.build_receipt_sha256)
        return 0
    fd = body.take_shared_lock()
    try:
        return build(gate, body, guard, plan, stage, data, state, args.resume_plan_sha256)
    finally:
        os.close(fd)


if __name__ == "__main__":
    raise SystemExit(main())
