export function productCopy(locale: VeilLocale, key: VeilCopyKey): string {
  return (locale === 'zh-Hant' ? zhHant : locale === 'zh' ? zh : en)[key];
}

export function productLocale(languageTag: string | undefined): VeilLocale {
  const canonical = systemLocale(languageTag ?? 'en');
  return canonical === 'zh-Hant' ? 'zh-Hant' : canonical === 'zh-Hans' ? 'zh' : 'en';
}
