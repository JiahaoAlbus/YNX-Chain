import {createDocsSessionTransport} from './product-session-transport.js';

export const docsWriteScopes = Object.freeze(['docs.write', 'files.write']);
const keyPattern = /^[A-Za-z0-9_-]{16,128}$/;
function encodeContent(content) {
  if (typeof content !== 'string') throw new TypeError('Document content must be text');
  const bytes = new TextEncoder().encode(content);
  if (bytes.length > 8 * 1024 * 1024) throw new TypeError('Document exceeds 8 MB');
  let binary = '';
  for (let offset = 0; offset < bytes.length; offset += 8192) binary += String.fromCharCode(...bytes.subarray(offset, offset + 8192));
  return btoa(binary);
}

// A prepared operation owns one immutable request body and one business key.
// Fresh session proofs are generated by transport for each explicit attempt.
export function createDocsWriteClient({adapter, origin, fetchImpl = globalThis.fetch, keyFactory = () => globalThis.crypto.randomUUID()}) {
  const request = createDocsSessionTransport({adapter, origin, fetchImpl});
  const operations = new WeakMap();
  function prepare(method, path, body) {
    const idempotencyKey = keyFactory();
    if (!keyPattern.test(idempotencyKey)) throw new TypeError('Invalid Docs write idempotency key');
    const operation = Object.freeze({method, path, body: JSON.stringify(body), idempotencyKey});
    operations.set(operation, {pending: null, blocked: false});
    return operation;
  }
  return {
    resumePrepared(saved) {
      if (!saved || !keyPattern.test(saved.idempotencyKey) || typeof saved.body !== 'string' || saved.body.length > 12 * 1024 * 1024 ||
        !((saved.method === 'POST' && saved.path === '/api/v1/objects') || (saved.method === 'PUT' && /^\/api\/v1\/objects\/[^/]+\/document$/.test(saved.path)))) throw new TypeError('Stored Docs write is invalid; preserve it for reconciliation');
      JSON.parse(saved.body);
      const operation = Object.freeze({method: saved.method, path: saved.path, body: saved.body, idempotencyKey: saved.idempotencyKey});
      operations.set(operation, {pending: null, blocked: false});
      return operation;
    },
    prepareCreate({name, parentId = '', kind = 'doc', content = ''}) {
      if (typeof name !== 'string' || !name.trim() || !['doc', 'folder'].includes(kind)) throw new TypeError('Document or folder name required');
      return prepare('POST', '/api/v1/objects', kind === 'folder'
        ? {parentId, kind, name}
        : {parentId, kind, name, mime: 'text/plain', content: encodeContent(content), encryption: {clientSide: false}});
    },
    prepareSave({id, baseVersion, content}) {
      if (typeof id !== 'string' || !id || !Number.isInteger(baseVersion) || baseVersion < 1) throw new TypeError('Document id and base version required');
      return prepare('PUT', `/api/v1/objects/${encodeURIComponent(id)}/document`, {baseVersion, content: encodeContent(content)});
    },
    async send(operation, {signal} = {}) {
      const record = operations.get(operation);
      if (!record) throw new TypeError('Use a prepared Docs write operation');
      if (record.blocked) {
        const error = new Error('Read and reconcile the actual document before preparing another write.');
        error.code = 'WRITE_OUTCOME_UNCERTAIN';
        error.reconciliationRequired = true;
        throw error;
      }
      if (record.pending) return record.pending;
      const execute = async () => {
        const response = await request(operation.path, {
          method: operation.method, body: operation.body, idempotencyKey: operation.idempotencyKey,
          headers: {'Content-Type': 'application/json'}, scopes: [...docsWriteScopes], signal,
        });
        let body;
        try { body = await response.json(); } catch {}
        if (!response.ok) {
          const error = new Error(response.status === 409 ? 'Docs write needs conflict or outcome reconciliation.' : 'Docs write was not confirmed. Preserve your draft.');
          error.status = response.status;
          if (typeof body?.code === 'string' && /^[A-Z][A-Z0-9_]{0,95}$/.test(body.code)) error.code = body.code;
          if (response.status === 409 && body?.current && typeof body.current === 'object') error.current = body.current;
          error.reconciliationRequired = error.code === 'WRITE_OUTCOME_UNCERTAIN' || error.code === 'IDEMPOTENCY_KEY_CONFLICT';
          if (error.reconciliationRequired) record.blocked = true;
          throw error;
        }
        if (!body || typeof body.id !== 'string') {
          record.blocked = true;
          const error = new Error('Docs returned no identifiable write receipt. Read the actual document before another write.');
          error.reconciliationRequired = true;
          throw error;
        }
        return {object: body, replayed: response.headers.get('Idempotency-Replayed') === 'true'};
      };
      record.pending = execute();
      try { return await record.pending; } finally { record.pending = null; }
    },
  };
}
