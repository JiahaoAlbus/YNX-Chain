import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtemp, readFile, rename, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { fileURLToPath } from "node:url";
import path from "node:path";
import { canonicalizeSbom, serializeCanonicalSbom } from "./sbom-canonical.mjs";

const walletRoot = fileURLToPath(new URL("..", import.meta.url));
const committedPath = path.join(walletRoot, "sbom.cdx.json");
const packageDocument = JSON.parse(
  await readFile(path.join(walletRoot, "package.json"), "utf8"),
);
const packageLockDocument = JSON.parse(
  await readFile(path.join(walletRoot, "package-lock.json"), "utf8"),
);
const packageManagerMatch = /^npm@(\d+\.\d+\.\d+)$/.exec(packageDocument.packageManager ?? "");
assert.ok(packageManagerMatch, "Wallet packageManager must pin an exact npm version");
const npmVersion = packageManagerMatch[1];
const platformSpecificPackages = new Set(
  Object.entries(packageLockDocument.packages ?? {})
    .filter(([, value]) => value.optional === true && (value.os || value.cpu))
    .map(([packagePath, value]) => {
      const marker = "node_modules/";
      const offset = packagePath.lastIndexOf(marker);
      assert.ok(offset >= 0 && value.version, `invalid platform package lock entry: ${packagePath}`);
      return `${packagePath.slice(offset + marker.length)}@${value.version}`;
    }),
);
const writeMode = process.argv.includes("--write");
const toolPath = path.join(
  walletRoot,
  "node_modules",
  "@cyclonedx",
  "cyclonedx-npm",
  "bin",
  "cyclonedx-npm-cli.js",
);

function run(command, args) {
  const result = spawnSync(command, args, {
    cwd: walletRoot,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
  if (result.error) throw result.error;
  assert.equal(
    result.status,
    0,
    `${command} failed\n${result.stdout}\n${result.stderr}`,
  );
  return `${result.stdout}\n${result.stderr}`;
}

function sha256(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

const npmTreeOutput = run("npm", ["ls", "--omit=dev", "--all", "--json"]);
assert.equal(
  npmTreeOutput.includes("ELSPROBLEMS"),
  false,
  "npm production tree contains ELSPROBLEMS",
);

const tempDir = await mkdtemp(path.join(tmpdir(), "ynx-wallet-sbom-"));
const generatedPath = path.join(tempDir, "sbom.cdx.json");

try {
  const lockViewManifest = structuredClone(packageDocument);
  const lockView = structuredClone(packageLockDocument);
  const walletAuthPath = "../../packages/wallet-auth";
  const walletAuthName = "@ynx-chain/wallet-auth";
  const walletAuth = lockView.packages?.[walletAuthPath];
  assert.ok(walletAuth?.version, "Wallet Auth lock entry is required");
  lockViewManifest.dependencies[walletAuthName] = walletAuth.version;
  lockView.packages[""].dependencies[walletAuthName] = walletAuth.version;
  lockView.packages[`node_modules/${walletAuthName}`] = { ...walletAuth };
  delete lockView.packages[walletAuthPath];
  await writeFile(path.join(tempDir, "package.json"), `${JSON.stringify(lockViewManifest, null, 2)}\n`, { mode: 0o600 });
  await writeFile(path.join(tempDir, "package-lock.json"), `${JSON.stringify(lockView, null, 2)}\n`, { mode: 0o600 });

  const generatorOutput = run(process.execPath, [
    toolPath,
    "--package-lock-only",
    "--output-reproducible",
    "--output-file",
    generatedPath,
    "--output-format",
    "JSON",
    "--spec-version",
    "1.6",
    "--omit",
    "dev",
    "--",
    path.join(tempDir, "package.json"),
  ]);
  assert.equal(
    generatorOutput.includes("ELSPROBLEMS"),
    false,
    "CycloneDX generation reported ELSPROBLEMS",
  );

  const rawSbom = JSON.parse(await readFile(generatedPath, "utf8"));
  const sbom = canonicalizeSbom(rawSbom, { npmVersion, platformSpecificPackages });
  const generatedBytes = serializeCanonicalSbom(sbom);
  assert.equal(sbom.bomFormat, "CycloneDX");
  assert.equal(sbom.specVersion, "1.6");
  assert.equal(sbom.metadata?.component?.group, "@ynx-chain");
  assert.equal(sbom.metadata?.component?.name, "wallet-app");
  assert.equal(sbom.metadata?.component?.version, packageDocument.version);

  const tools = sbom.metadata?.tools?.components ?? [];
  const generator = tools.find(
    (component) =>
      component.group === "@cyclonedx" && component.name === "cyclonedx-npm",
  );
  assert.equal(
    generator?.version,
    "6.0.0",
    "SBOM must be generated by pinned cyclonedx-npm 6.0.0",
  );

  const components = sbom.components ?? [];
  const dependencies = sbom.dependencies ?? [];
  assert.ok(components.length > 0, "SBOM contains no components");
  assert.ok(dependencies.length > 0, "SBOM contains no dependency graph");

  const refs = components.map((component) => component["bom-ref"]);
  assert.equal(
    new Set(refs).size,
    refs.length,
    "SBOM component bom-ref values must be unique",
  );

  for (const component of components) {
    assert.ok(component.type, `component missing type: ${component.name ?? "unknown"}`);
    assert.ok(component.name, "component missing name");
    assert.ok(component.version, `component missing version: ${component.name}`);
    assert.ok(
      Array.isArray(component.licenses) && component.licenses.length > 0,
      `component missing license metadata: ${component.name}@${component.version}`,
    );
  }

  const generatedHash = sha256(generatedBytes);
  if (writeMode) {
    const replacementPath = `${committedPath}.next`;
    await rm(replacementPath, { force: true });
    await writeFile(replacementPath, generatedBytes, { mode: 0o644 });
    await rename(replacementPath, committedPath);
  } else {
    const committedBytes = await readFile(committedPath);
    assert.equal(
      sha256(committedBytes),
      generatedHash,
      "committed sbom.cdx.json is stale; run npm run sbom:generate",
    );
  }

  console.log(
    `wallet SBOM ${writeMode ? "generated" : "verified"}: ${components.length} components, ${dependencies.length} dependency nodes, complete license metadata, sha256 ${generatedHash}`,
  );
} finally {
  await rm(tempDir, { recursive: true, force: true });
}
