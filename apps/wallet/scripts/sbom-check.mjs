import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtemp, readFile, rename, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { fileURLToPath } from "node:url";
import path from "node:path";

const walletRoot = fileURLToPath(new URL("..", import.meta.url));
const committedPath = path.join(walletRoot, "sbom.cdx.json");
const packageDocument = JSON.parse(
  await readFile(path.join(walletRoot, "package.json"), "utf8"),
);
const writeMode = process.argv.includes("--write");
const toolPath = path.join(
  walletRoot,
  "node_modules",
  "@cyclonedx",
  "cyclonedx-npm",
  "bin",
  "cyclonedx-npm-cli.js",
);

function run(command, args) {
  const result = spawnSync(command, args, {
    cwd: walletRoot,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
  if (result.error) throw result.error;
  assert.equal(
    result.status,
    0,
    `${command} failed\n${result.stdout}\n${result.stderr}`,
  );
  return `${result.stdout}\n${result.stderr}`;
}

function sha256(bytes) {
  return createHash("sha256").update(bytes).digest("hex");
}

const npmTreeOutput = run("npm", ["ls", "--omit=dev", "--all", "--json"]);
assert.equal(
  npmTreeOutput.includes("ELSPROBLEMS"),
  false,
  "npm production tree contains ELSPROBLEMS",
);

const tempDir = await mkdtemp(path.join(tmpdir(), "ynx-wallet-sbom-"));
const generatedPath = path.join(tempDir, "sbom.cdx.json");

try {
  const generatorOutput = run(process.execPath, [
    toolPath,
    "--output-reproducible",
    "--output-file",
    generatedPath,
    "--output-format",
    "JSON",
    "--spec-version",
    "1.6",
    "--omit",
    "dev",
  ]);
  assert.equal(
    generatorOutput.includes("ELSPROBLEMS"),
    false,
    "CycloneDX generation reported ELSPROBLEMS",
  );

  const generatedBytes = await readFile(generatedPath);
  const sbom = JSON.parse(generatedBytes.toString("utf8"));
  assert.equal(sbom.bomFormat, "CycloneDX");
  assert.equal(sbom.specVersion, "1.6");
  assert.equal(sbom.metadata?.component?.group, "@ynx-chain");
  assert.equal(sbom.metadata?.component?.name, "wallet-app");
  assert.equal(sbom.metadata?.component?.version, packageDocument.version);

  const tools = sbom.metadata?.tools?.components ?? [];
  const generator = tools.find(
    (component) =>
      component.group === "@cyclonedx" && component.name === "cyclonedx-npm",
  );
  assert.equal(
    generator?.version,
    "6.0.0",
    "SBOM must be generated by pinned cyclonedx-npm 6.0.0",
  );

  const components = sbom.components ?? [];
  const dependencies = sbom.dependencies ?? [];
  assert.ok(components.length > 0, "SBOM contains no components");
  assert.ok(dependencies.length > 0, "SBOM contains no dependency graph");

  const refs = components.map((component) => component["bom-ref"]);
  assert.equal(
    new Set(refs).size,
    refs.length,
    "SBOM component bom-ref values must be unique",
  );

  for (const component of components) {
    assert.ok(component.type, `component missing type: ${component.name ?? "unknown"}`);
    assert.ok(component.name, "component missing name");
    assert.ok(component.version, `component missing version: ${component.name}`);
    assert.ok(
      Array.isArray(component.licenses) && component.licenses.length > 0,
      `component missing license metadata: ${component.name}@${component.version}`,
    );
  }

  const generatedHash = sha256(generatedBytes);
  if (writeMode) {
    const replacementPath = `${committedPath}.next`;
    await rm(replacementPath, { force: true });
    await writeFile(replacementPath, generatedBytes, { mode: 0o644 });
    await rename(replacementPath, committedPath);
  } else {
    const committedBytes = await readFile(committedPath);
    assert.equal(
      sha256(committedBytes),
      generatedHash,
      "committed sbom.cdx.json is stale; run npm run sbom:generate",
    );
  }

  console.log(
    `wallet SBOM ${writeMode ? "generated" : "verified"}: ${components.length} components, ${dependencies.length} dependency nodes, complete license metadata, sha256 ${generatedHash}`,
  );
} finally {
  await rm(tempDir, { recursive: true, force: true });
}
