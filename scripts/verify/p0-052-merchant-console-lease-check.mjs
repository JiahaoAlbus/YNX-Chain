assert.equal(leases.light.taskId,"P0-052");
assert.equal(leases.light.status,"RELEASED_SOURCE_CHECKPOINT");
assert.equal(lease.status,"CONSUMED_RELEASED_SOURCE_CHECKPOINT");
assert.equal(lease.checkpointCommit,"f3d36ab5785f910f3114c4a080f2c2551aabe656");
assert.equal(lease.result.standardWalletSourceImplemented,true);
assert.equal(lease.result.actualProviderApprovalVisible,false);
