import fs from "node:fs";
import path from "node:path";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"../..");
const read=p=>JSON.parse(fs.readFileSync(path.join(root,p),"utf8"));
const gitBlob=p=>{const b=fs.readFileSync(path.join(root,p));return createHash("sha1").update(Buffer.from(`blob ${b.length}\0`)).update(b).digest("hex");};
const acceptance=read("release/integration/p0-wallet-connectivity/acceptance/shop-android-retirement-candidate.json");
const retirement=read("release/integration/p0-wallet-connectivity/client-retirement.json");
const queue=read("release/integration/p0-wallet-connectivity/integration-queue.json");
const handoffPath="release/integration/p0-wallet-connectivity/evidence/shop-android-client-retirement-owner-handoff.json";
const contractPath="release/integration/p0-wallet-connectivity/evidence/shop-android-client-retirement-contract.json";
const handoff=read(handoffPath), contract=read(contractPath);
const assert=(v,m)=>{if(!v)throw new Error(m);};
assert(gitBlob(handoffPath)==="2d8f3b528b73e7d429913f314353a6716ac127d5","owner handoff blob");
assert(gitBlob(contractPath)==="06e466bdfd38f689f65726c3f3b1e4bc7d699074","owner contract blob");
assert(handoff.featureSourceCommit==="c614501353d7631a6e20da7431ac858c2e5a8868","feature commit");
assert(handoff.status==="CANDIDATE" && handoff.activation.includes("prohibited"),"owner activation boundary");
assert(contract.status==="CANDIDATE" && contract.activation.includes("prohibited"),"contract activation boundary");
assert(acceptance.decision==="CANDIDATE_CONSUMED_ACTIVATION_BLOCKED_SHARED_TUPLE","decision");
assert(acceptance.tupleReview.requestedRetiredAt===null,"retiredAt must remain null");
assert(acceptance.tupleReview.platformDiscriminatorPresent===false,"platform discriminator");
assert(acceptance.tupleReview.tupleUniquenessProved===false,"tuple uniqueness");
assert(acceptance.tupleReview.stillSupportedNativeClientEvidence.some(x=>x.platform==="ios"&&x.sharesExactTuple),"iOS collision");
assert(acceptance.tupleReview.stillSupportedWebClientEvidence.some(x=>x.platform==="web-pwa"&&x.sharesExactTuple),"Web collision");
assert(acceptance.executionLease.issued===false && acceptance.executionLease.status==="BLOCKED_BEFORE_ISSUE","lease must be absent");
for(const k of ["featureIntegratedCentral","featureDeployedPublic","publicRetirementVerified","installedClientVerified","remoteUninstallClaim","productionSigned","storeReleased"])assert(acceptance.truth[k]===false,`truth ${k}`);
assert(acceptance.truth.existingPublicRuntimeRemainsVerified===true && acceptance.truth.currentPublicRuntimeContainsFeature===false,"existing runtime boundary");
const client=retirement.clients.find(x=>x.product==="shop"&&x.platform==="android");
assert(client&&client.retiredAt===null,"central retiredAt");
assert(client.walletProtocolCandidate.executionLeaseIssued===false&&client.walletProtocolCandidate.tupleUniquenessProved===false,"central candidate block");
const task=queue.tasks.find(x=>x.taskId==="P0-011");
assert(task.status==="WALLET_PROTOCOL_CANDIDATE_CONSUMED_ACTIVATION_BLOCKED_SHARED_TUPLE","queue status");
assert(task.walletProtocolCandidate.featureCommit===acceptance.ownerCandidate.featureCommit&&task.walletProtocolCandidate.handoffCommit===acceptance.ownerCandidate.handoffCommit,"queue source");
assert(task.walletProtocolCandidate.executionLeaseIssued===false&&task.tupleReview.tupleUniquenessProved===false,"queue lease");
console.log("PASS P0-011 Wallet Protocol candidate consumed; Android-only activation blocked by shared iOS/Web tuple and retiredAt=null; no execution lease issued");
