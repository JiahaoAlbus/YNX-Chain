#!/usr/bin/env node
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"../..");
const read=p=>JSON.parse(fs.readFileSync(path.join(root,p),"utf8"));
const leases=read("release/integration/p0-wallet-connectivity/execution-leases.json");
const locks=read("release/integration/p0-wallet-connectivity/path-locks.json");
const queue=read("release/integration/p0-wallet-connectivity/integration-queue.json");
const lease=read("release/integration/p0-wallet-connectivity/execution/p0-060-search-source-lease-20260821.json");
assert.equal(leases.heavy.owner,null);
assert.equal(leases.light.owner,null);
assert.equal(leases.light.taskId,"P0-060");
assert.equal(leases.light.status,"RELEASED_SEARCH_SOURCE_CHECKPOINT");
assert.equal(lease.status,"RELEASED_SEARCH_SOURCE_CHECKPOINT");
assert.equal(lease.checkpointCommit,"a3b78490a7945fa982bfe78c8be75396b013a649");
const lock=locks.locks.find(x=>x.taskId==="P0-060");
assert.equal(lock.path,"apps/search/**");
assert.equal(lock.status,"CHECKPOINT_REACHED");
assert.equal(lock.checkpointCommit,"a3b78490a7945fa982bfe78c8be75396b013a649");
assert.equal(queue.tasks.filter(x=>x.taskId==="P0-060").length,1);
const search=queue.tasks.find(x=>x.taskId==="P0-060");
assert.equal(search.status,"SOURCE_CHECKPOINT_REACHED_LIGHT_RELEASED");
assert.equal(search.standardWalletSourceImplemented,true);
assert.equal(search.publicVerified,false);
assert.equal(search.computerControlVerified,false);
assert.equal(queue.tasks.find(x=>x.taskId==="P0-059").sourceAccepted,false);
console.log("PASS P0-060 Search source checkpoint is released while public and ComputerControl gates remain false");
