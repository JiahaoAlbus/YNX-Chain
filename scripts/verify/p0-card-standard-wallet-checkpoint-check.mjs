#!/usr/bin/env node
import assert from "node:assert/strict";
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const readJson = (p) => JSON.parse(fs.readFileSync(path.join(root, p), "utf8"));
const sha256 = (p) => crypto.createHash("sha256").update(fs.readFileSync(path.join(root, p))).digest("hex");
const acceptance = readJson("release/integration/p0-wallet-connectivity/acceptance/card-standard-wallet-checkpoint-644f977c-20260820.json");
const evidence = readJson("release/integration/wallet-product-session-card-owner-checkpoint-20260820.json");
const matrix = readJson("release/integration/p0-wallet-connectivity/wallet-product-session-consumer-status-matrix-20260820.json");
const queue = readJson("release/integration/p0-wallet-connectivity/integration-queue.json");
assert.equal(acceptance.ownerCheckpointCommit, "644f977c678f99f786d4c9c527d9519db51ff8cf");
assert.equal(sha256(acceptance.checkpointEvidence.path), acceptance.checkpointEvidence.sha256);
assert.equal(fs.statSync(path.join(root, acceptance.checkpointEvidence.path)).size, acceptance.checkpointEvidence.bytes);
assert.equal(evidence.commit, acceptance.productSourceCommit);
assert.equal(evidence.walletAuthSourceCommit, "24cc3218c2cdc00c50dc3caa563652083afbd861");
assert.equal(evidence.ownerReportedVerification.npmTestPassed, 21);
assert.equal(evidence.ownerReportedVerification.npmTestFailed, 0);
assert.equal(evidence.ownerReportedVerification.typecheckPassed, true);
assert.equal(evidence.directSourceEvidence.standardWalletRemainsConnected, true);
assert.equal(evidence.directSourceEvidence.privateSessionFailureState, "PRIVATE_SERVICE_DEGRADED");
assert.equal(evidence.directSourceEvidence.developerMessageExposedToUi, false);
assert.equal(evidence.remainingSecurityGap.callerSuppliedArbitraryHttpsGatewayStillAccepted, true);
assert.deepEqual(matrix.standardWalletOnlyProducts, ["card"]);
assert.equal(matrix.productsMigratedV2, 0);
assert.equal(matrix.products.card.classification, "standard-wallet-only");
assert.equal(matrix.products.card.productSessionV2GatewayEvidenced, false);
assert.equal(matrix.products.card.visiblePlatformEvidenced, false);
assert.equal(matrix.products.card.migratedV2, false);
assert.ok(matrix.products.card.blockers.some((entry) => entry.includes("caller-supplied arbitrary HTTPS Gateway")));
assert.deepEqual(acceptance.matrix.standardWalletOnlyProducts, ["card"]);
assert.equal(acceptance.matrix.productsMigratedV2, 0);
assert.equal(acceptance.truth.cardMigratedV2, false);
assert.equal(acceptance.truth.integratedCentral, false);
assert.equal(acceptance.truth.aggregatePublic, false);
const task = queue.tasks.find((entry) => entry.taskId === "P0-020");
assert.ok(task);
assert.equal(task.status, "CARD_STANDARD_WALLET_ONLY_V2_BLOCKED");
assert.equal(task.productsMigrated, 0);
console.log("PASS Card 644f977c: standard Wallet and canonical errors accepted; arbitrary Gateway, legacy routes and missing visible v2 evidence keep Card unmigrated at 0/12");
