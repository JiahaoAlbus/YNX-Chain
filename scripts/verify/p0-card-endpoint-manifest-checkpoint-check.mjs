#!/usr/bin/env node
import assert from "node:assert/strict";
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "../..");
const readJson = (p) => JSON.parse(fs.readFileSync(path.join(root, p), "utf8"));
const sha256 = (p) => crypto.createHash("sha256").update(fs.readFileSync(path.join(root, p))).digest("hex");
const acceptance = readJson("release/integration/p0-wallet-connectivity/acceptance/card-endpoint-manifest-checkpoint-b789ec97-20260820.json");
const evidence = readJson(acceptance.checkpointEvidence.path);
const matrix = readJson("release/integration/p0-wallet-connectivity/wallet-product-session-consumer-status-matrix-v2-20260820.json");
const queue = readJson("release/integration/p0-wallet-connectivity/integration-queue.json");
assert.equal(acceptance.ownerCheckpointCommit, "b789ec97374c6bc2fe926797f1fb35b4bfbba971");
assert.equal(sha256(acceptance.checkpointEvidence.path), acceptance.checkpointEvidence.sha256);
assert.equal(fs.statSync(path.join(root, acceptance.checkpointEvidence.path)).size, acceptance.checkpointEvidence.bytes);
assert.equal(evidence.commit, "2c2e117e42b4daacf96cd74abc6844c72398c522");
assert.equal(evidence.ownerTrackingRefExact, true);
assert.equal(evidence.independentLsRemoteReadback, false);
assert.equal(evidence.directSourceEvidence.callerSuppliedGatewayRemoved, true);
assert.equal(evidence.directSourceEvidence.environmentSuppliedGatewayRemoved, true);
assert.equal(evidence.directSourceEvidence.hostileHttpsHostRejected, true);
assert.equal(evidence.directSourceEvidence.credentialsRejected, true);
assert.equal(evidence.directSourceEvidence.pathRejected, true);
assert.equal(evidence.directSourceEvidence.queryRejected, true);
assert.equal(evidence.directSourceEvidence.unavailableManifestFailsClosedBeforeNetwork, true);
assert.equal(evidence.directSourceEvidence.standardWalletConnectionPreserved, true);
assert.equal(evidence.directSourceEvidence.legacyCardRoutesAreV2Evidence, false);
assert.equal(evidence.ownerReportedVerification.npmTestPassed, 22);
assert.equal(evidence.truth.migratedV2, false);
assert.equal(matrix.products.card.fixedEndpointManifestConsumed, true);
assert.equal(matrix.products.card.appGatewayAvailable, false);
assert.equal(matrix.products.card.productSessionV2GatewayEvidenced, false);
assert.equal(matrix.productsMigratedV2, 0);
const task = queue.tasks.find((entry) => entry.taskId === "P0-021");
assert.ok(task);
assert.equal(task.status, "CARD_ENDPOINT_PINNED_APP_GATEWAY_UNAVAILABLE");
assert.equal(task.productsMigrated, 0);
console.log("PASS Card b789ec97: endpoint injection closed and manifest pinned; unavailable App Gateway, legacy routes and missing visible evidence keep Card standard-wallet-only at 0/12");
